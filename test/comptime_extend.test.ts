import { expect, test } from "vite-plus/test";

import build_and_check_output from "./build_and_check_output";
import { compile_module } from "./spec/_helpers.ts";

// Stage-6 follow-up: peer members on EXISTING types — `extend struct
// #{t.name} { ... }` inside a file-scope `#for` arm. The extension merges
// before the statement walk (so the generated methods are checked and
// emitted exactly like in-body methods), and the body's `self` parameters
// are retyped from the spliced target name.

test("a generated extend adds methods and out-of-line conformance per type", async () => {
	await build_and_check_output(
		`
import System

trait Named {
	func label = (self, out string)
}

@entity
pub struct User {
	pub var int count
}

@entity
pub struct Order {
	pub var int count
}

#for t of META.types_with("entity") {
	extend struct #{t.name}: Named {
		pub func label = (self, out string) {
			return t.name
		}
		pub func bump = (ref self, out int) {
			self.count = self.count + 1
			return self.count
		}
	}
}

pub func main = () {
	var u = User(1)
	Console.write_line(u.label())
	Console.write_line(u.bump().to_string())
	var o = Order(10)
	Console.write_line(o.label())
	Console.write_line(o.bump().to_string())
}
`,
		"comptime_extend_members",
		"User\n2\nOrder\n11\n",
		true,
		{ js: true },
	);
});

test("a generated extend may target a type declared later in the file", async () => {
	const errors = compile_module(`
		#for t of META.types_with("entity") {
			extend struct #{t.name} {
				pub func label = (self, out string) {
					return t.name
				}
			}
		}

		@entity
		pub struct Later {
			pub var int id
		}
	`);
	expect(errors).toEqual([]);
});

test("a generated extend of an unknown type names the resolved target", () => {
	const errors = compile_module(`
		#for i of 0..2 {
			extend struct missing_#{i} {
				pub func label = (self, out string) {
					return "x"
				}
			}
		}
	`);
	expect(errors.some((e) => e.message.includes("Cannot extend unknown type: missing_0"))).toBe(
		true,
	);
	expect(errors.some((e) => e.message.includes("Cannot extend unknown type: missing_1"))).toBe(
		true,
	);
});

test("generated extensions are independent per iteration (no shared body)", () => {
	// Two targets, two different receiver types: a shared ExtendNode would
	// type-check `self` against one target and reject the other.
	const errors = compile_module(`
		@entity
		pub struct A {
			pub var int n
		}
		@entity
		pub struct B {
			pub var int n
		}
		#for t of META.types_with("entity") {
			extend struct #{t.name} {
				pub func get = (self, out int) {
					return self.n
				}
			}
		}
	`);
	expect(errors).toEqual([]);
});

test("a body-scope generated extend is a loud error, not a silent no-op", () => {
	const errors = compile_module(`
		pub struct A {
			pub var int n
		}
		pub func main = () {
			#for i of 0..1 {
				extend struct A {
					pub func get = (self, out int) {
						return self.n
					}
				}
			}
		}
	`);
	expect(
		errors.some((e) => e.message.includes("generated by a '#for' at body scope is never merged")),
	).toBe(true);
});
