#!/usr/bin/env node
/**
 * Derives the editor-specific query sets from `queries/` (the
 * nvim-treesitter-convention originals):
 *
 *   editors/helix/queries/nomen/  — Helix capture names, and highlight
 *                                    patterns in REVERSED order: Helix gives
 *                                    the first matching pattern precedence,
 *                                    where Neovim and Zed take the last.
 *   editors/zed/languages/nomen/  — Zed capture names (highlights,
 *                                    injections); Zed's brackets, indents and
 *                                    outline queries are hand-written there.
 *
 * Usage: node scripts/build-editor-queries.mjs [--check]
 *
 * With --check, writes nothing and exits non-zero when a generated file is
 * out of date.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const check = process.argv.includes("--check");

const HEADER =
	"; GENERATED by scripts/build-editor-queries.mjs from queries/ — do not edit.\n" +
	"; Edit the originals in queries/ and re-run `npm run build-queries`.\n\n";

/** nvim-treesitter capture → Helix scope. Unlisted captures pass through. */
const HELIX_NAMES = {
	"comment.documentation": "comment.block.documentation",
	"constant.macro": "constant",
	"variable.builtin": "variable.builtin",
	property: "variable.other.member",
	"function.call": "function",
	"function.method.call": "function.method",
	module: "namespace",
	"string.escape": "constant.character.escape",
	character: "constant.character",
	number: "constant.numeric",
	boolean: "constant.builtin.boolean",
	"keyword.import": "keyword.control.import",
	"keyword.type": "keyword.storage.type",
	"keyword.modifier": "keyword.storage.modifier",
	"keyword.return": "keyword.control.return",
	"keyword.conditional": "keyword.control.conditional",
	"keyword.repeat": "keyword.control.repeat",
	"keyword.exception": "keyword.control.exception",
	"keyword.coroutine": "keyword.control",
};

/** nvim-treesitter capture → Zed name. Unlisted captures pass through. */
const ZED_NAMES = {
	"comment.documentation": "comment.doc",
	"variable.builtin": "variable.special",
	"constant.macro": "constant",
	"function.call": "function",
	"function.method.call": "function.method",
	module: "namespace",
};

/** Splits a query file into its blank-line-separated chunks. */
function chunks(source) {
	return source
		.split(/\n\s*\n/)
		.map((c) => c.trim())
		.filter(Boolean);
}

const is_comment_only = (chunk) => chunk.split("\n").every((l) => l.trim().startsWith(";"));

/** Renames `@capture` names (leaving `@_private` ones) and drops `@spell`. */
function rename(source, names) {
	return source
		.replace(/ @spell\b/g, "")
		.replace(/@([a-z][a-z.]*)/g, (whole, name) =>
			Object.hasOwn(names, name) ? `@${names[name]}` : whole,
		);
}

function read(name) {
	return fs.readFileSync(path.join(root, "queries", name), "utf8");
}

const outputs = new Map();

// --- Helix ---
{
	const dir = "editors/helix/queries/nomen";
	const patterns = chunks(read("highlights.scm")).filter((c) => !is_comment_only(c));
	outputs.set(
		`${dir}/highlights.scm`,
		HEADER + rename(patterns.reverse().join("\n\n"), HELIX_NAMES) + "\n",
	);
	outputs.set(`${dir}/injections.scm`, HEADER + read("injections.scm"));
	// Helix knows plain local.definition / local.reference captures.
	outputs.set(
		`${dir}/locals.scm`,
		HEADER + read("locals.scm").replace(/@local\.definition\.[a-z]+/g, "@local.definition"),
	);
}

// --- Zed ---
{
	const dir = "editors/zed/languages/nomen";
	outputs.set(`${dir}/highlights.scm`, HEADER + rename(read("highlights.scm"), ZED_NAMES));
	outputs.set(`${dir}/injections.scm`, HEADER + read("injections.scm"));
}

let stale = 0;
for (const [file, content] of outputs) {
	const full = path.join(root, file);
	const current = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : undefined;
	if (current === content) continue;
	if (check) {
		console.log(`out of date: ${file}`);
		stale++;
		continue;
	}
	fs.mkdirSync(path.dirname(full), { recursive: true });
	fs.writeFileSync(full, content);
	console.log(`wrote ${file}`);
}
if (check && stale > 0) {
	console.log("run `npm run build-queries` to regenerate");
	process.exit(1);
}
