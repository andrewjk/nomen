/**
 * Embeds the System library into the site so the REPL can compile inside a
 * Cloudflare Worker (no filesystem). Run via `pnpm bundle:core`; `dev` and
 * `build` regenerate it automatically.
 *
 * The generated module holds the library's TYPE MAP (not just raw sources) —
 * the same `Library` `get_library()` builds on Node — with file paths
 * rewritten under a virtual `/core`, so the Worker needs no disk paths and
 * never runs the library scanner at request time.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { get_library } from "../../src/lib.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../..");
const core = process.env.NOMEN_CORE
	? path.resolve(process.env.NOMEN_CORE)
	: path.join(repo, "core");
const out_file = path.join(repo, "site/src/lib/core-library.generated.ts");

const library = get_library(core);
const virtual_root = "/core";

// The GUI namespaces (System::Controls) are native AppKit views — they can
// never run in a browser, and they are half the library's source. Leaving them
// out keeps the Worker small; referencing one is a compile-time "unknown type"
// instead of a runtime unsupported-feature error.
const DROPPED = /\/Controls\//;
const to_virtual = (file: string): string =>
	virtual_root + "/" + path.relative(core, file).split(path.sep).join("/");

// One copy of each file's source; entries reference it by path.
const kept = (entry: { path: string }): boolean => !DROPPED.test(entry.path);

const files = new Map<string, string>();
for (const entry of [...library.types.values(), ...library.functions.values()]) {
	if (kept(entry)) files.set(to_virtual(entry.path), entry.source);
}

const data = {
	name: library.name,
	dir: virtual_root,
	files: Object.fromEntries([...files.entries()].sort(([a], [b]) => a.localeCompare(b))),
	types: [...library.types]
		.filter(([, entry]) => kept(entry))
		.map(([name, entry]) => [
			name,
			{
				name: entry.name,
				path: to_virtual(entry.path),
				deps: entry.deps,
				...(entry.namespace !== undefined ? { namespace: entry.namespace } : {}),
			},
		]),
	functions: [...library.functions]
		.filter(([, entry]) => kept(entry))
		.map(([name, entry]) => [
			name,
			{
				name: entry.name,
				path: to_virtual(entry.path),
				deps: entry.deps,
				...(entry.namespace !== undefined ? { namespace: entry.namespace } : {}),
			},
		]),
	namespaces: [...library.namespaces].map(([namespace, names]) => [namespace, [...names]]),
};

const source = `// Generated by site/scripts/bundle-core.ts — do not edit.
// The System library's type map, embedded for the Cloudflare Worker REPL.
import type { SerializedLibrary } from "./core.ts";

export const CORE_LIBRARY: SerializedLibrary = ${JSON.stringify(data)};
`;

fs.writeFileSync(out_file, source);
const size = (fs.statSync(out_file).size / 1024).toFixed(0);
console.log(
	`bundle-core: wrote ${path.relative(repo, out_file)} (${size} kB, ${files.size} files)`,
);
